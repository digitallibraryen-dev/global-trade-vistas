// Generate a date between start and end based on index
function generateDate(index: number, total: number): string {
  const start = new Date("2019-11-11").getTime();
  const end = new Date("2025-12-16").getTime();
  const step = (end - start) / (total - 1);
  const d = new Date(start + step * index);
  return d.toISOString().split("T")[0];
}

// Seeded pseudo-random for consistent ratings
function seededRating(index: number): number {
  const x = Math.sin(index * 9301 + 49297) * 49297;
  const r = x - Math.floor(x);
  if (r < 0.02) return 1;
  if (r < 0.05) return 2;
  if (r < 0.15) return 3;
  if (r < 0.45) return 4;
  return 5;
}

