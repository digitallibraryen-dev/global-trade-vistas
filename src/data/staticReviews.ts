// Deterministically pick 112 indices to receive profile images
function getProfileImageIndices(total: number, count: number): Set<number> {
  const indices = new Set<number>();
  let seed = 42;
  while (indices.size < count && indices.size < total) {
    seed = (seed * 16807 + 12345) % 2147483647;
    indices.add(seed % total);
  }
  return indices;
}

